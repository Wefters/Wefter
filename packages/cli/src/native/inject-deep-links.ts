/**
 * Registers each environment's deep links (from `deepLinks` in `wefter.config.json`) with both native
 * projects. Links that arrive are handed to the web app by the shell (`onDeepLink` in core).
 *
 * - Android: each environment is a product flavor, so its intent filters go into the flavor's own
 *   `src/<env>/AndroidManifest.xml`, which Gradle merges into `MainActivity`. Verified domains get an
 *   `autoVerify` filter (App Links).
 * - iOS: `Info.plist` is shared by every configuration, so it lists the schemes as build settings
 *   (`$(WEFTER_URL_SCHEME_1)`, …) that each `Environment-<env>.xcconfig` fills in. Verified domains go into a
 *   per-environment entitlements file (Universal Links), chosen with `CODE_SIGN_ENTITLEMENTS`.
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { androidPathAttribute, type ResolvedDeepLinks } from "../config/deep-links.js";

/** First line of every file this module generates, so a later sync knows it may replace or delete it. */
const GENERATED_HEADER =
  "<!-- Generated by `wefter sync` from deepLinks in wefter.config.json. Changes here are overwritten. -->";

/** Markers around the generated `CFBundleURLTypes` entry in `Info.plist`. */
export const IOS_URL_TYPES_START = "<!-- WEFTER-URL-TYPES-START -->";
export const IOS_URL_TYPES_END = "<!-- WEFTER-URL-TYPES-END -->";

/** Markers around the generated deep link settings in each `Environment-<env>.xcconfig`. */
export const IOS_XCCONFIG_DEEP_LINKS_START = "// WEFTER-DEEPLINKS-START";
export const IOS_XCCONFIG_DEEP_LINKS_END = "// WEFTER-DEEPLINKS-END";

/** Prefix of the build settings that hold an environment's schemes, numbered from 1. */
const IOS_SCHEME_SETTING = "WEFTER_URL_SCHEME_";

/** No settings: what an environment gets when the config does not mention it. */
const NO_DEEP_LINKS: ResolvedDeepLinks = { schemes: [], domains: [], paths: [] };

/** The flavor manifest that holds an environment's intent filters. */
export function androidFlavorManifestPath(appModuleDir: string, env: string): string {
  return join(appModuleDir, "src", env, "AndroidManifest.xml");
}

/** The entitlements file of an environment, next to `Info.plist`. */
export function iosEntitlementsPath(appDir: string, env: string): string {
  return join(appDir, `Entitlements-${env}.entitlements`);
}

/**
 * Writes `content` to a generated file, or deletes the file when `content` is `null`. A file that exists
 * without the generated header was written by hand and is left alone; replacing it is an error.
 *
 * @throws {Error} When a hand-written file is in the way of generated content.
 */
function writeGeneratedFile(path: string, content: string | null, purpose: string): void {
  const existing = existsSync(path) ? readFileSync(path, "utf-8") : null;
  const ownedByWefter = existing === null || existing.includes(GENERATED_HEADER);

  if (content === null) {
    if (existing !== null && ownedByWefter) rmSync(path);
    return;
  }
  if (!ownedByWefter) {
    throw new Error(
      `${path} was not written by wefter sync, so it cannot hold the ${purpose}. Move its contents ` +
        `elsewhere (or delete it) and run \`wefter sync\` again.`,
    );
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content, "utf-8");
}

/** A `VIEW` intent filter with the categories that let browsers and other apps open it. */
function renderIntentFilter(dataLines: string[], autoVerify: boolean): string {
  return [
    `            <intent-filter${autoVerify ? ' android:autoVerify="true"' : ""}>`,
    `                <action android:name="android.intent.action.VIEW" />`,
    `                <category android:name="android.intent.category.DEFAULT" />`,
    `                <category android:name="android.intent.category.BROWSABLE" />`,
    ...dataLines.map((line) => `                ${line}`),
    `            </intent-filter>`,
  ].join("\n");
}

/**
 * The flavor manifest for one environment: a filter per custom scheme, and an `autoVerify` filter per
 * verified domain limited to its paths. `null` when the environment has no deep links.
 */
export function renderAndroidFlavorManifest(links: ResolvedDeepLinks): string | null {
  if (links.schemes.length === 0 && links.domains.length === 0) return null;

  const pathLines = links.paths.map((path) => {
    const { name, value } = androidPathAttribute(path);
    return `<data android:${name}="${value}" />`;
  });
  const filters = [
    ...links.schemes.map((scheme) => renderIntentFilter([`<data android:scheme="${scheme}" />`], false)),
    ...links.domains.map((domain) =>
      renderIntentFilter([`<data android:scheme="https" />`, `<data android:host="${domain}" />`, ...pathLines], true),
    ),
  ];

  return [
    `<?xml version="1.0" encoding="utf-8"?>`,
    GENERATED_HEADER,
    `<manifest xmlns:android="http://schemas.android.com/apk/res/android">`,
    `    <application>`,
    `        <activity android:name=".MainActivity">`,
    ...filters,
    `        </activity>`,
    `    </application>`,
    `</manifest>`,
    "",
  ].join("\n");
}

/**
 * Writes each environment's flavor manifest under `appModuleDir/src/<env>/`, and removes generated ones
 * for environments that no longer have deep links.
 *
 * @throws {Error} When a hand-written flavor manifest is in the way.
 */
export function injectDeepLinksAndroid(appModuleDir: string, byEnv: Record<string, ResolvedDeepLinks>): void {
  for (const [env, links] of Object.entries(byEnv)) {
    writeGeneratedFile(
      androidFlavorManifestPath(appModuleDir, env),
      renderAndroidFlavorManifest(links),
      `deep links of the "${env}" environment`,
    );
  }
}

/**
 * The `CFBundleURLTypes` entry with `slotCount` scheme slots, each filled per configuration from an
 * xcconfig build setting. Nothing when no environment has a scheme.
 */
function renderIosUrlTypes(slotCount: number): string {
  if (slotCount === 0) return "";
  const slots = Array.from(
    { length: slotCount },
    (_, i) => `\t\t\t\t<string>$(${IOS_SCHEME_SETTING}${i + 1})</string>`,
  );
  return [
    `\t<key>CFBundleURLTypes</key>`,
    `\t<array>`,
    `\t\t<dict>`,
    `\t\t\t<key>CFBundleURLName</key>`,
    `\t\t\t<string>$(PRODUCT_BUNDLE_IDENTIFIER)</string>`,
    `\t\t\t<key>CFBundleURLSchemes</key>`,
    `\t\t\t<array>`,
    ...slots,
    `\t\t\t</array>`,
    `\t\t</dict>`,
    `\t</array>`,
    "",
  ].join("\n");
}

/**
 * The xcconfig lines of one environment: a value for every scheme slot and, with verified domains, the
 * entitlements file. An environment with fewer schemes than slots repeats its first one; with none, the
 * slots hold the bundle id, a scheme no other app uses, since an empty value is not a valid scheme.
 */
function renderXcconfigBlock(links: ResolvedDeepLinks, slotCount: number, entitlements: string | null): string {
  const lines = Array.from({ length: slotCount }, (_, i) => {
    const value = links.schemes[i] ?? links.schemes[0] ?? "$(PRODUCT_BUNDLE_IDENTIFIER)";
    return `${IOS_SCHEME_SETTING}${i + 1} = ${value}`;
  });
  if (entitlements) lines.push(`CODE_SIGN_ENTITLEMENTS = ${entitlements}`);
  return [IOS_XCCONFIG_DEEP_LINKS_START, ...lines, IOS_XCCONFIG_DEEP_LINKS_END].join("\n");
}

/** The entitlements file listing an environment's verified domains, or `null` when it has none. */
export function renderIosEntitlements(domains: string[]): string | null {
  if (domains.length === 0) return null;
  return [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">`,
    GENERATED_HEADER,
    `<plist version="1.0">`,
    `<dict>`,
    `\t<key>com.apple.developer.associated-domains</key>`,
    `\t<array>`,
    ...domains.map((domain) => `\t\t<string>applinks:${domain}</string>`),
    `\t</array>`,
    `</dict>`,
    `</plist>`,
    "",
  ].join("\n");
}

/** Replaces the text between two markers, or adds the marked block with `insert` when the markers are missing. */
function replaceMarkedBlock(
  text: string,
  start: string,
  end: string,
  block: string,
  insert: (text: string) => string,
): string {
  const pattern = new RegExp(`${start}[\\s\\S]*?${end}`);
  return pattern.test(text) ? text.replace(pattern, block) : insert(text);
}

/**
 * Registers each environment's schemes and verified domains with the iOS project: the scheme slots in
 * `Info.plist`, their values and the entitlements file in every `Environment-<env>.xcconfig` under
 * `configDir`, and the entitlements files next to `Info.plist`. Environments without settings in `byEnv`
 * get none.
 *
 * @throws {Error} When `Info.plist` already declares `CFBundleURLTypes` outside the markers (a second key
 * would silently replace the first), or a hand-written entitlements file is in the way.
 */
export function injectDeepLinksIos(
  infoPlistPath: string,
  configDir: string,
  byEnv: Record<string, ResolvedDeepLinks>,
): void {
  const appDir = dirname(infoPlistPath);
  const envs = readdirSync(configDir)
    .map((name) => /^Environment-(.+)\.xcconfig$/.exec(name)?.[1])
    .filter((env): env is string => env !== undefined);
  const linksOf = (env: string) => byEnv[env] ?? NO_DEEP_LINKS;
  const slotCount = Math.max(0, ...envs.map((env) => linksOf(env).schemes.length));

  const plist = readFileSync(infoPlistPath, "utf-8");
  const urlTypes = `${IOS_URL_TYPES_START}\n${renderIosUrlTypes(slotCount)}\t${IOS_URL_TYPES_END}`;
  if (!plist.includes(IOS_URL_TYPES_START) && plist.includes("<key>CFBundleURLTypes</key>") && slotCount > 0) {
    throw new Error(
      `${infoPlistPath} already declares CFBundleURLTypes. Move its schemes to "deepLinks.schemes" in ` +
        `wefter.config.json, or wrap the entry in ${IOS_URL_TYPES_START} / ${IOS_URL_TYPES_END} so wefter ` +
        `sync can manage it.`,
    );
  }
  if (plist.includes(IOS_URL_TYPES_START) || slotCount > 0) {
    const updated = replaceMarkedBlock(plist, IOS_URL_TYPES_START, IOS_URL_TYPES_END, urlTypes, (text) =>
      text.replace(/(<dict>)/, `$1\n\t${urlTypes}`),
    );
    writeFileSync(infoPlistPath, updated, "utf-8");
  }

  for (const env of envs) {
    const links = linksOf(env);
    const entitlementsPath = iosEntitlementsPath(appDir, env);
    const entitlements = renderIosEntitlements(links.domains);
    writeGeneratedFile(entitlementsPath, entitlements, `associated domains of the "${env}" environment`);

    const xcconfigPath = join(configDir, `Environment-${env}.xcconfig`);
    const relativeEntitlements = entitlements ? `${basename(appDir)}/${basename(entitlementsPath)}` : null;
    const block = renderXcconfigBlock(links, slotCount, relativeEntitlements);
    const xcconfig = readFileSync(xcconfigPath, "utf-8");
    const updated = replaceMarkedBlock(
      xcconfig,
      IOS_XCCONFIG_DEEP_LINKS_START,
      IOS_XCCONFIG_DEEP_LINKS_END,
      block,
      (text) => `${text.replace(/\n*$/, "\n")}${block}\n`,
    );
    writeFileSync(xcconfigPath, updated, "utf-8");
  }
}
